from tokenizer import detokenize_tensor_to_string, tokenize_string

def do_simple_tests(model, training_inputs):
    """
    Simple tests to see how the model behaves
    """

    device = next(model.parameters()).device

    model.eval()

    print()
    print()

    print("-- test 1 --")
    print("\033[34mBlue text\033[0m is generated by the model.\n")

    from chat import continue_sentence

    sentence = training_inputs[0]
    print(detokenize_tensor_to_string(sentence), end="\033[34m")

    sentence = continue_sentence(sentence, 200, include_input_sentence=False)

    print(detokenize_tensor_to_string(sentence), end="\033[0m")

    print()
    print()

    print("-- test 2 --")

    while(True):
        prompt = "Input a message: "
        msg = input(prompt)

        # move printing cursor to the end of the last line to make the generated text to apear continuously
        import shutil
        cols = shutil.get_terminal_size().columns
        col = (len(prompt) + len(msg)) % cols + 1
        print(f"\033[A\33[{col}G", end="", flush=True)


        print("\033[34m", end="")
        print(detokenize_tensor_to_string(continue_sentence(tokenize_string(msg).to(device), 200, include_input_sentence=False)))
        print("\033[0m")
        print()